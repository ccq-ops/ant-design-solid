import { execFile } from 'node:child_process'
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { promisify } from 'node:util'

import ts from 'typescript'

const execFileAsync = promisify(execFile)
const repositoryRoot = path.resolve(import.meta.dirname, '..')
const configPath = path.join(repositoryRoot, 'scripts', 'antd-api-audit.config.json')
const snapshotPath = path.join(repositoryRoot, 'scripts', 'antd-api-baseline.json')
const reportPath = path.join(repositoryRoot, 'docs', 'generated', 'antd-api-audit.md')
const localEntry = path.join(repositoryRoot, 'packages', 'components', 'src', 'index.ts')

function parseArgs(args) {
  return {
    check: args.includes('--check'),
    refresh: args.includes('--refresh'),
  }
}

async function readJson(filePath) {
  return JSON.parse(await readFile(filePath, 'utf8'))
}

function collectModuleExports(entry) {
  const program = ts.createProgram([entry], {
    allowJs: false,
    jsx: ts.JsxEmit.Preserve,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    skipLibCheck: true,
    target: ts.ScriptTarget.ES2022,
  })
  const sourceFile = program.getSourceFile(entry)
  if (!sourceFile) {
    throw new Error(`Could not load TypeScript entry: ${entry}`)
  }

  const checker = program.getTypeChecker()
  const symbol = checker.getSymbolAtLocation(sourceFile)
  if (!symbol) {
    throw new Error(`Could not resolve module exports: ${entry}`)
  }

  return checker
    .getExportsOfModule(symbol)
    .map((item) => item.getName())
    .filter((name) => name !== 'default')
    .sort()
}

function difference(left, right) {
  const rightSet = new Set(right)
  return left.filter((item) => !rightSet.has(item))
}

function createSnapshot(version, upstreamExports, localExports, classifications = {}) {
  const missingFromLocal = difference(upstreamExports, localExports)
  return {
    version,
    generatedAt: new Date().toISOString(),
    upstreamExports,
    localExports,
    missingFromLocal,
    classifiedMissing: Object.fromEntries(
      missingFromLocal
        .filter((name) => classifications[name])
        .map((name) => [name, classifications[name]]),
    ),
    unclassifiedMissing: missingFromLocal.filter((name) => !classifications[name]),
    solidSpecificExports: difference(localExports, upstreamExports),
  }
}

function formatList(items) {
  if (items.length === 0) return '- None\n'
  return items.map((item) => `- \`${item}\``).join('\n') + '\n'
}

function createReport(snapshot) {
  return `# Generated Ant Design API Export Audit

> This file is generated by \`pnpm api:audit:refresh\`. Do not edit it manually.
>
> Upstream baseline: \`antd@${snapshot.version}\`
>
> Generated at: ${snapshot.generatedAt}

## Summary

| Metric | Count |
| --- | ---: |
| Upstream root exports | ${snapshot.upstreamExports.length} |
| Local root exports | ${snapshot.localExports.length} |
| Upstream exports missing locally | ${snapshot.missingFromLocal.length} |
| Classified missing exports | ${Object.keys(snapshot.classifiedMissing).length} |
| Unclassified missing exports | ${snapshot.unclassifiedMissing.length} |
| Solid-specific/local-only exports | ${snapshot.solidSpecificExports.length} |

The lists below are an inventory, not an instruction to copy React-only APIs. Every missing export
must be classified as \`implement\`, \`rename\`, \`deprecated-compat\`, \`React-only\`, or
\`intentionally-unsupported\` before changing the public API.

## Upstream Exports Missing Locally

${formatList(snapshot.missingFromLocal)}
## Classified Missing Exports

${
  Object.entries(snapshot.classifiedMissing)
    .map(
      ([name, classification]) =>
        `- \`${name}\` — **${classification.status}**: ${classification.reason}`,
    )
    .join('\n') || '- None'
}

## Unclassified Missing Exports

${formatList(snapshot.unclassifiedMissing)}
## Solid-specific or Local-only Exports

${formatList(snapshot.solidSpecificExports)}
`
}

async function downloadAntd(version) {
  const directory = await mkdtemp(path.join(tmpdir(), 'ant-design-solid-api-audit-'))
  const { stdout } = await execFileAsync(
    'npm',
    ['pack', `antd@${version}`, '--pack-destination', directory, '--json'],
    { cwd: repositoryRoot, maxBuffer: 1024 * 1024 * 20 },
  )
  const packResult = JSON.parse(stdout)
  const filename = packResult[0]?.filename
  if (!filename) {
    throw new Error(`npm pack did not return a tarball for antd@${version}`)
  }

  await execFileAsync('tar', ['-xzf', path.join(directory, filename), '-C', directory])
  return {
    directory,
    entry: path.join(directory, 'package', 'es', 'index.d.ts'),
  }
}

async function refresh(config) {
  const download = await downloadAntd(config.version)
  try {
    const upstreamExports = collectModuleExports(download.entry)
    const localExports = collectModuleExports(localEntry)
    const snapshot = createSnapshot(
      config.version,
      upstreamExports,
      localExports,
      config.classifications,
    )
    await mkdir(path.dirname(reportPath), { recursive: true })
    await writeFile(snapshotPath, `${JSON.stringify(snapshot, null, 2)}\n`)
    await writeFile(reportPath, createReport(snapshot))
    console.log(
      `Updated API baseline for antd@${config.version}: ${snapshot.unclassifiedMissing.length} unclassified missing, ${snapshot.solidSpecificExports.length} local-only exports.`,
    )
  } finally {
    await rm(download.directory, { recursive: true, force: true })
  }
}

async function check(config) {
  const expected = await readJson(snapshotPath)
  if (expected.version !== config.version) {
    throw new Error(
      `API baseline uses antd@${expected.version}, but config requires antd@${config.version}. Run pnpm api:audit:refresh.`,
    )
  }

  const localExports = collectModuleExports(localEntry)
  const actual = createSnapshot(
    expected.version,
    expected.upstreamExports,
    localExports,
    config.classifications,
  )
  const stableExpected = {
    ...expected,
    generatedAt: actual.generatedAt,
  }

  if (JSON.stringify(actual) !== JSON.stringify(stableExpected)) {
    const added = difference(localExports, expected.localExports)
    const removed = difference(expected.localExports, localExports)
    throw new Error(
      [
        'Public API exports changed without refreshing the Ant Design API baseline.',
        added.length ? `Added: ${added.join(', ')}` : '',
        removed.length ? `Removed: ${removed.join(', ')}` : '',
        'Run pnpm api:audit:refresh and review the generated diff.',
      ]
        .filter(Boolean)
        .join('\n'),
    )
  }

  console.log(
    `API baseline matches antd@${expected.version}: ${actual.unclassifiedMissing.length} unclassified missing, ${actual.solidSpecificExports.length} local-only exports.`,
  )
}

async function main() {
  const args = parseArgs(process.argv.slice(2))
  if (args.check === args.refresh) {
    throw new Error('Choose exactly one mode: --check or --refresh')
  }

  const config = await readJson(configPath)
  if (args.refresh) {
    await refresh(config)
  } else {
    await check(config)
  }
}

await main()
